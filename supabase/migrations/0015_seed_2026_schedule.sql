-- The full 2026 regular season schedule: 18 weeks, 272 games.
--
-- Matchups and kickoff times are known the moment the league publishes the
-- schedule; lines are not. Splitting them is what this migration is for. Every
-- game row lands now with its teams and kickoff, and with spread, total,
-- over_odds, under_odds and line_source left NULL. Lines are attached weekly as
-- the book posts them, and a week only opens once every game on its slate has a
-- complete one — the rule SPEC §5 gives sync-slate.
--
-- That also shrinks sync-slate to its real job. It no longer has to discover a
-- slate, reconcile teams, or invent week rows; it fills in numbers on rows that
-- already exist and flips the week to `open` when none are missing.
--
-- Source: nflverse (github.com/nflverse/nfldata, data/games.csv), the published
-- 2026 regular season. 272 games across weeks 1-18, 13 to 16 per week
-- because of byes. nflverse abbreviates the Rams LA; this table uses LAR, so
-- that one is remapped. Every other abbreviation matches teams.abbr.
--
-- Times are written as `America/New_York` literals rather than UTC. Postgres
-- resolves the offset from the tz database, so the November DST shift is its
-- problem rather than a number I computed and could get wrong — which is the
-- failure SPEC §4 warns about for locks_at. The stored value is still
-- timestamptz, i.e. UTC; only the way it is written here is Eastern.
--
-- Every week is `upcoming`. Nothing here opens a week, and nothing here touches
-- the 2025 demo week — see OPERATIONS.md for the cutover.

-- locks_at is Thursday 4:00 PM ET, except where the slate opens earlier than
-- that, in which case it is 30 minutes before the first kickoff — SPEC's holiday
-- rule, applied to the real calendar. Three weeks need it in 2026:
--
--   Week  1  opens Wed 9 Sep 20:20 (season opener)     -> lock Wed 19:50
--   Week 12  opens Wed 25 Nov 20:00 (Thanksgiving week) -> lock Wed 19:30
--   Week 18  opens Sun 10 Jan 13:00 (no Thursday game)  -> lock Sun 12:30
--
-- A lock after the first kickoff would let someone pick a game already in
-- progress, so the earlier of the two always wins.

